import fs from "node:fs";
import path from "node:path";

if (process.env.NITRO_PRESET === "vercel" || process.env.VERCEL) {
  console.log(
    "[prerender] Skipping prerender for Vercel preset (handled by Vercel Build Output API).",
  );
  process.exit(0);
}

const PORT = process.env.PRERENDER_PORT || "4399";
process.env.PORT = PORT;
process.env.SITE_URL = process.env.SITE_URL || "https://cpaleasing.com";

console.log(`[prerender] Starting internal server on port ${PORT}...`);
const serverModule = await import("../.output/server/index.mjs");

const routes = [
  "/",
  "/about",
  "/contact",
  "/leadership",
  "/aircraft-leasing",
  "/aviation-assets",
  "/our-approach",
  "/gift-city",
];

let failed = false;

for (const route of routes) {
  const url = `http://localhost:${PORT}${route}`;
  const res = await fetch(url);
  if (!res.ok) {
    console.error(`[prerender] Failed to render ${route}: status ${res.status}`);
    failed = true;
    continue;
  }
  const html = await res.text();
  const outDir = route === "/" ? ".output/public" : path.join(".output/public", route.slice(1));
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, "index.html"), html, "utf8");
  console.log(`[prerender] Generated ${outDir}/index.html (${html.length} bytes)`);
}

// Extra files so .output/public works as a fully static site (served by Nginx, no Node server).
// sitemap.xml is generated by the server entry; robots.txt gets a Sitemap line; 404.html is the
// app's own not-found page (status 404 is expected here).
const siteOrigin = process.env.SITE_URL.replace(/\/+$/, "");

const sitemapRes = await fetch(`http://localhost:${PORT}/sitemap.xml`);
if (sitemapRes.ok) {
  fs.writeFileSync(".output/public/sitemap.xml", await sitemapRes.text(), "utf8");
  console.log("[prerender] Generated .output/public/sitemap.xml");
} else {
  console.error(`[prerender] Failed to render /sitemap.xml: status ${sitemapRes.status}`);
  failed = true;
}

const robotsPath = ".output/public/robots.txt";
const robots = fs.existsSync(robotsPath)
  ? fs.readFileSync(robotsPath, "utf8")
  : "User-agent: *\nAllow: /\n";
if (!/^Sitemap:/im.test(robots)) {
  fs.writeFileSync(
    robotsPath,
    `${robots.trimEnd()}\n\nSitemap: ${siteOrigin}/sitemap.xml\n`,
    "utf8",
  );
  console.log("[prerender] Added Sitemap line to .output/public/robots.txt");
}

const notFoundRes = await fetch(`http://localhost:${PORT}/__prerender-not-found__`);
if (notFoundRes.status === 404) {
  fs.writeFileSync(".output/public/404.html", await notFoundRes.text(), "utf8");
  console.log("[prerender] Generated .output/public/404.html");
} else {
  console.error(`[prerender] Expected 404 for not-found page, got ${notFoundRes.status}`);
  failed = true;
}

if (failed) {
  console.error("[prerender] Static page generation FAILED.");
  process.exit(1);
}

console.log("[prerender] Static page generation completed successfully.");

// Close server gracefully if exposed
if (serverModule?.default?.close) {
  await serverModule.default.close();
}

setTimeout(() => {
  process.exit(0);
}, 200);
